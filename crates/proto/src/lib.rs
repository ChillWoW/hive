//! outcode-proto — wire types shared by the Rust backend and the React frontend.
//!
//! The TypeScript side is generated from these definitions into `src/proto/`
//! by `cargo test -p outcode-proto`; never edit it by hand.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// What starts a run: a prompt for an agent working in `cwd`.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct RunRequest {
    /// The folder the agent works in. Empty: the user's home folder.
    pub cwd: String,
    pub prompt: String,
}

/// One step of an agent's turn, normalized across CLIs. A turn ends with
/// [`AgentEvent::Done`]; a failed one reports [`AgentEvent::Error`] first.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "camelCase", rename_all_fields = "camelCase")]
pub enum AgentEvent {
    /// More of the reply's text, to append.
    TextDelta { text: String },
    Error { message: String },
    Done { status: DoneStatus },
}

/// How a turn ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub enum DoneStatus {
    Completed,
    /// Stopped by the user.
    Interrupted,
    /// Failed; an [`AgentEvent::Error`] said why.
    Errored,
}

#[cfg(test)]
mod export {
    use std::fmt::Write as _;
    use std::fs;
    use std::path::PathBuf;

    use ts_rs::{Config, TS};

    use super::*;

    /// Regenerates `src/proto/` from scratch, so a renamed or deleted type
    /// leaves no stale file behind.
    #[test]
    fn export_bindings() {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/proto");
        if dir.exists() {
            fs::remove_dir_all(&dir).unwrap();
        }
        let cfg = Config::new().with_out_dir(&dir).with_large_int("number");

        RunRequest::export_all(&cfg).unwrap();
        AgentEvent::export_all(&cfg).unwrap();

        let mut modules: Vec<String> = fs::read_dir(&dir)
            .unwrap()
            .filter_map(|e| e.unwrap().file_name().into_string().ok())
            .filter_map(|name| name.strip_suffix(".ts").map(str::to_owned))
            .collect();
        modules.sort();
        let mut index =
            String::from("// Generated by outcode-proto. Do not edit this file manually.\n\n");
        for module in modules {
            writeln!(index, "export type {{ {module} }} from \"./{module}\";").unwrap();
        }
        fs::write(dir.join("index.ts"), index).unwrap();
    }
}
