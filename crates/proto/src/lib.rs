#[cfg(test)]
mod export {
    use std::fmt::Write as _;
    use std::fs;
    use std::path::{Path, PathBuf};

    use ts_rs::{Config, TS};

    use super::*;

    /// Regenerates `src/proto/` from scratch, so a renamed or deleted type
    /// leaves no stale file behind.
    #[test]
    fn export_bindings() {
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/proto");
        if dir.exists() {
            fs::remove_dir_all(&dir).unwrap();
        }
        // serde writes u64/i64 as plain JSON numbers, and JSON.parse reads
        // them as `number`; every count and timestamp here fits in 2^53.
        let cfg = Config::new().with_out_dir(&dir).with_large_int("number");

        RunRequest::export_all(&cfg).unwrap();
        AgentEvent::export_all(&cfg).unwrap();
        Model::export_all(&cfg).unwrap();
        UserInputAnswer::export_all(&cfg).unwrap();
        Message::export_all(&cfg).unwrap();
        Chat::export_all(&cfg).unwrap();
        Session::export_all(&cfg).unwrap();
        Command::export_all(&cfg).unwrap();
        Settings::export_all(&cfg).unwrap();
        MessagesUpdate::export_all(&cfg).unwrap();
        ChatsUpdate::export_all(&cfg).unwrap();
        HarnessCatalog::export_all(&cfg).unwrap();
        ProviderStatus::export_all(&cfg).unwrap();
        SignInMethod::export_all(&cfg).unwrap();
        SignInStarted::export_all(&cfg).unwrap();
        GitRepo::export_all(&cfg).unwrap();
        NewWorktree::export_all(&cfg).unwrap();
        WorkspaceEntry::export_all(&cfg).unwrap();
        DirectoryEntry::export_all(&cfg).unwrap();

        let mut modules = Vec::new();
        collect_modules(&dir, "", &mut modules);
        modules.sort();
        let mut index =
            String::from("// Generated by hive-proto. Do not edit this file manually.\n\n");
        for module in modules {
            let name = module.rsplit('/').next().unwrap();
            writeln!(index, "export type {{ {name} }} from \"./{module}\";").unwrap();
        }

        // The one value the frontend needs from Rust: settings defaults, for
        // first paint, browser dev and per-setting reset.
        let defaults = serde_json::to_string_pretty(&Settings::default()).unwrap();
        fs::write(
            dir.join("defaults.ts"),
            format!(
                "// Generated by hive-proto from `Settings::default()`. Do not edit this file manually.\n\
                 import type {{ Settings }} from \"./Settings\";\n\n\
                 export const DEFAULT_SETTINGS: Settings = {defaults};\n"
            ),
        )
        .unwrap();
        writeln!(index, "\nexport {{ DEFAULT_SETTINGS }} from \"./defaults\";").unwrap();

        fs::write(dir.join("index.ts"), index).unwrap();
    }

    /// `.ts` files under `dir` as extensionless paths relative to the root;
    /// ts-rs puts foreign types like `serde_json/JsonValue` in subdirectories.
    fn collect_modules(dir: &Path, prefix: &str, out: &mut Vec<String>) {
        for entry in fs::read_dir(dir).unwrap() {
            let entry = entry.unwrap();
            let name = entry.file_name().into_string().unwrap();
            if entry.file_type().unwrap().is_dir() {
                collect_modules(&entry.path(), &format!("{prefix}{name}/"), out);
            } else if let Some(stem) = name.strip_suffix(".ts") {
                out.push(format!("{prefix}{stem}"));
            }
        }
    }
}
